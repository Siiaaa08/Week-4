package reflection.intermediatelevel.dynamicmethodinvocation;

public class DynamicMethod {
        public void add(int a, int b){
            System.out.println(a+b);
        }
        public void subs(int a,int b){
            System.out.println(
                    a-b
            );
        }
        public void multi(int a,int b){
            System.out.println(a*b);
        }
    }


